<h2>6. Escalera de Selarón (bajando hacia Lapa)</h2>
<p>La escalera cubierta de azulejos del artista chileno Jorge Selarón conecta Santa Teresa con Lapa y es uno de los lugares más fotografiados de Río. Está al pie del cerro: visítala al bajar y termina el día en Lapa.</p>

<h2>7. Miradores y comida de boteco</h2>
<p>Varios miradores informales en las curvas ofrecen vistas tan buenas como las oficiales, sin colas ni multitudes. A mediodía, los restaurantes sirven cocina minera y carioca con cerveza bien fría en mesas en la acera.</p>

